import { config as loadDotenv } from "dotenv";
import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { stringify } from "yaml";
import { z } from "zod";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
loadDotenv({ path: path.join(packageRoot, ".env") });

const FixtureSchema = z.object({
    id: z.string().min(1),
    description: z.string().min(1),
    tags: z.array(z.string()).default([]),
    request: z.record(z.string(), z.unknown()),
    expected: z.record(z.string(), z.unknown()),
});

type Fixture = z.infer<typeof FixtureSchema>;

const FIXTURES_DIR = path.join(packageRoot, "fixtures", "roadmap");
const GENERATED_DIR = path.join(packageRoot, "generated");
const GENERATED_TESTS_PATH = path.join(GENERATED_DIR, "roadmap-tests.yaml");

const ASSERTIONS = [
    { type: "javascript", value: "file://assertions/roadmap-assertions.ts:assertRoadmapValidShape" },
    { type: "javascript", value: "file://assertions/roadmap-assertions.ts:assertRoadmapStageCount" },
    { type: "javascript", value: "file://assertions/roadmap-assertions.ts:assertBeginnerDegreeThenJobPath" },
    { type: "javascript", value: "file://assertions/roadmap-assertions.ts:assertHowAndGainFields" },
    { type: "javascript", value: "file://assertions/roadmap-assertions.ts:assertNoFluffCapabilities" },
    { type: "javascript", value: "file://assertions/roadmap-assertions.ts:assertDegreeTimelineYears" },
    { type: "javascript", value: "file://assertions/roadmap-assertions.ts:assertNoiseRemoved" },
    { type: "javascript", value: "file://assertions/roadmap-assertions.ts:assertActionPlans" },
] as const;

const loadFixtures = async (): Promise<Fixture[]> => {
    const files = (await readdir(FIXTURES_DIR)).filter((name) => name.endsWith(".json")).sort();
    const fixtures: Fixture[] = [];
    for (const fileName of files) {
        const raw = await readFile(path.join(FIXTURES_DIR, fileName), "utf8");
        const parsed = FixtureSchema.safeParse(JSON.parse(raw));
        if (!parsed.success) {
            throw new Error(`Invalid roadmap fixture ${fileName}: ${parsed.error.message}`);
        }
        fixtures.push(parsed.data);
    }
    return fixtures;
};

const main = async (): Promise<void> => {
    const fixtures = await loadFixtures();
    const tests = fixtures.map((fixture) => ({
        description: fixture.id,
        vars: {
            caseId: fixture.id,
            request: fixture.request,
            expected: fixture.expected,
            caseDescription: fixture.description,
        },
        tags: fixture.tags,
        assert: [...ASSERTIONS],
    }));

    await mkdir(GENERATED_DIR, { recursive: true });
    const yamlBody = [
        "# AUTO-GENERATED by scripts/generate-roadmap-promptfoo-tests.ts",
        "# Do not edit by hand. Re-run: npm run update:roadmap",
        `# Source: fixtures/roadmap (count=${tests.length})`,
        stringify(tests),
    ].join("\n");
    await writeFile(GENERATED_TESTS_PATH, yamlBody, "utf8");
    console.info(`Wrote ${tests.length} roadmap Promptfoo tests to ${GENERATED_TESTS_PATH}`);
};

main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
});
